// Deliberately limited to the two flat, primitive foundation DTOs. Fail on drift.
const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const source = 'docs/architecture/openapi/integration-v1.json';
const target = 'apps/web/src/lib/api/generated/foundation.ts';
const bytes = fs.readFileSync(path.join(root, source));
const doc = JSON.parse(bytes);
const sha = crypto.createHash('sha256').update(bytes).digest('hex');
let text = `// Generated by tools/frontend/generate-foundation-contracts.cjs. Do not edit.\n// Source: ${source}\n// SHA-256: ${sha}\n\n`;
for (const name of ['SystemStatusResponse', 'HealthResponse']) {
  const schema = doc.components.schemas[name];
  if (schema?.type !== 'object' || !schema.properties) throw Error(`Unsupported DTO: ${name}`);
  text += `export type ${name} = {\n`;
  for (const [key, property] of Object.entries(schema.properties)) {
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(key) || !['string', 'boolean'].includes(property.type) || property.nullable || property.$ref || property.enum)
      throw Error(`Unsupported property: ${name}.${key}; review generator before expanding scope.`);
    text += `  ${key}${schema.required?.includes(key) ? '' : '?'}: ${property.type};\n`;
  }
  text += '};\n\n';
}
text = text.trimEnd() + '\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path.join(root, target), 'utf8') !== text) throw Error('Generated foundation types are stale. Run the generator.');
  console.log('Foundation contract types match the saved OpenAPI.');
} else {
  fs.mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
  fs.writeFileSync(path.join(root, target), text);
  console.log(`Generated ${target}`);
}
